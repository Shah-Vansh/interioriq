"""M35 design chat: messages become generator options (tier, style, budget, skip/add, kitchen shape, seats) — never geometry or money; the
layout is re-generated by the deterministic planner; catalogue questions are answered from the database; Ollama off → rules work."""
import time
from decimal import Decimal

import pytest
from fastapi.testclient import TestClient

from app.main import app
from app.services import design_chat as dc

RUN = str(int(time.time()))[-6:]


@pytest.fixture(scope="module")
def client():
    with TestClient(app) as c: yield c


def hdr(c):
    return {"Authorization": "Bearer " + c.post("/api/auth/login", json={"email": "admin@interioriq.com", "password": "ChangeMe123!"}).json()["access_token"]}


def test_rules_reader():
    r = dc.rules("Make it cheaper and more scandinavian, no armchair, add a bookshelf, keep it under 2.5 lakh", "LIVING")
    assert r["tier"] == "BUDGET" and r["styles"] == ["scandinavian"] and r["skip"] == ["armchair"] and r["add"] == ["bookshelf"] and r["budget"] == Decimal("250000.00")
    assert dc.rules("L-shaped kitchen please", "KITCHEN")["kitchen_shape"] == "L"
    assert dc.rules("table for 6 people", "DINING")["seats"] == 6 and "budget" not in dc.rules("table for 6 people", "DINING")
    assert dc.rules("budget 80k", "STUDY")["budget"] == Decimal("80000.00")
    assert dc.rules("hello there", "LIVING") == {}
    assert dc.interpret("which wardrobes do we have under 60k?", "BEDROOM")["question"] is True
    o, b, said = dc.apply({"skip": ["armchair"], "tier": "BALANCED"}, None, {"add": ["armchair"], "tier": "PREMIUM"})
    assert o["skip"] == [] and o["tier"] == "PREMIUM" and len(said) == 2
    # an LLM answer is only used after strict cleaning
    assert dc._clean({"tier": "cheapest", "styles": ["gothic"], "skip": ["sofa", "armchair"], "budget_inr": "abc", "seats": 40}, "LIVING") == {"skip": ["armchair"]}


def test_chat_regenerates_and_answers_questions(client):
    h = hdr(client)
    pid = client.post("/api/projects", json={"project_number": f"IQ-CHAT-{RUN}", "name": "Chat flat"}, headers=h).json()["id"]
    rid = client.post(f"/api/projects/{pid}/rooms", json={"name": "Living", "room_type": "LIVING"}, headers=h).json()["id"]
    for l, v in (("Length", 5200), ("Width", 4000), ("Ceiling Height", 2900)): client.put(f"/api/rooms/{rid}/measurements", json={"label": l, "value": v, "source": "USER_VERIFIED"}, headers=h)
    r = client.post(f"/api/rooms/{rid}/design-chat", json={"message": "no armchair, cheaper please, under 3 lakh"}, headers=h).json()
    assert r["source"] == "rules" and r["options"]["tier"] == "BUDGET" and "armchair" in r["options"]["skip"] and r["budget"] == "300000.00"
    res = r["result"]; assert res and res["validation"]["valid"] and all(o["category"] != "Armchair" for o in res["objects"])
    assert "Done —" in r["reply"] and res["cost"]["grand_total"].replace(".", "").isdigit()
    r2 = client.post(f"/api/rooms/{rid}/design-chat", json={"message": "add the armchair back", "options": r["options"], "budget": r["budget"]}, headers=h).json()
    assert "armchair" not in r2["options"]["skip"]
    q = client.post(f"/api/rooms/{rid}/design-chat", json={"message": "Which sofas do we have under 1 lakh?"}, headers=h).json()
    assert q["result"] is None and q["items"] and all(Decimal(i["price"]) <= 100000 for i in q["items"]) and all(i["category"] == "Sofa" for i in q["items"])
    n = client.post(f"/api/rooms/{rid}/design-chat", json={"message": "hmm"}, headers=h).json()
    assert n["result"] is None and "didn't catch" in n["reply"]
